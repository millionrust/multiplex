#!/usr/bin/env python3
"""Project the existing Slate palette onto the browser terminal UI."""
import re
from pathlib import Path
root=Path(__file__).resolve().parents[2]
tokens={}
for block in (root/'design/tokens.toml').read_text().split('[[tokens]]')[1:]:
    key=re.search(r'key = "([^"]+)"',block)
    if key: tokens[key.group(1)]={mode:value for mode,value in re.findall(r'(light|dark) = "(#[0-9A-Fa-f]+)"',block)}
mapping={'bg':'color.bg.canvas','panel':'color.bg.surface','raised':'color.bg.container','line':'color.border.default','text':'color.text.primary','muted':'color.text.muted','faint':'color.text.secondary','accent':'color.action.primary','focus':'color.focus','hover':'color.bg.elevated','selected':'color.bg.container_high','scrollbar':'color.border.strong','brand-bg':'color.bg.container_high','brand-fg':'color.action.primary'}
css='/* Generated by scripts/build/browser-terminal-tokens.py from design/tokens.toml. */\n'
for mode in ['light','dark']:
    selector=':root' if mode=='light' else ':root[data-theme="dark"]'
    css+=selector+' {\n'+''.join(f'  --{name}: {tokens[token][mode]};\n' for name,token in mapping.items())+'}\n'
css+=':root { --term-bg: '+tokens['color.bg.terminal']['dark']+'; --term-text: '+tokens['color.text.primary']['dark']+'; }\n'
(root/'apps/web-terminal/app/assets/css/slate.css').write_text(css)
